const ALL_NAMES = [...new Set([...CITIES, ...Object.keys(PROVINCE_CAPITALS)])];

function entryFor(name, kind) {
  if (kind === 'province') {
    return { name, query: PROVINCE_CAPITALS[name] ?? name, kind };
  }
  return { name, query: name, kind };
}

// 捕获文本中最后出现的省市：
// - 「北京市/杭州市/吉林省」带后缀的按后缀判定；无后缀时城市优先（吉林 → 吉林市）
// - 多个地名时取位置最靠后的（最近提及优先）；位置相同取名字更长的
export function captureRegion(text) {
  if (typeof text !== 'string' || text.trim() === '') {
    return null;
  }
  let best = null;
  for (const name of ALL_NAMES) {
    let from = 0;
    for (;;) {
      const index = text.indexOf(name, from);
      if (index === -1) {
        break;
      }
      const suffix = text.slice(index + name.length, index + name.length + 1);
      const kind = suffix === '省' ? 'province' : 'city';
      const candidate = { ...entryFor(name, kind), index };
      if (best === null
        || candidate.index > best.index
        || (candidate.index === best.index && candidate.name.length > best.name.length)
        || (candidate.index === best.index && candidate.name.length === best.name.length && best.kind === 'province' && candidate.kind === 'city')) {
        best = candidate;
      }
      from = index + 1;
    }
  }
  return best;
}
