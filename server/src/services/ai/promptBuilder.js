// 当前本地时间（年月日时分）：供 AI 把「明天」「后天」等相对说法换算成绝对时间
function nowText() {
  const d = new Date();
  const p = n => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`;
}

// 上下文各栏标题与渲染顺序；仅渲染 context 中实际存在的键，避免出现大量空栏
const CONTEXT_TITLES = {
  now: '当前时间',
  weather: '天气（当前真实天气；source=captured 为对话中捕获的地区，source=client 为客户端所在地）',
  selfAccount: '本人账号',
  selfProfile: '本人用户资料',
  selfCards: '本人卡片（我的日程，含公开卡片库与私人卡片库）',
  participants: '参与人（账号 → 用户资料 / 卡片，含其私人卡片）',
  userList: '用户列表（账号 / userId / 与本人关系；invitable=true 才可邀请）',
  userInfo: '用户信息',
  schedules: '已有日程',
  currentCard: '当前卡片',
  conflicts: '时间冲突（服务器已判定，必须如实转达）',
  history: '历史对话'
};

// 在任务需求上方渲染上下文，让 AI 能基于「本人 + 各参与人」的真实日程与资料连续推理与推荐
function renderContext(context = {}) {
  const source = (context && typeof context === 'object') ? context : {};
  const defs = [];
  for (const key of Object.keys(CONTEXT_TITLES)) {
    if (key === 'now') {
      defs.push([CONTEXT_TITLES[key], source.now ?? nowText()]);
      continue;
    }
    if (!(key in source)) {
      continue;
    }
    defs.push([CONTEXT_TITLES[key], source[key]]);
  }
  return defs.map(([title, value]) => {
    const header = `【${title}】`;
    const isEmpty = value === null || value === undefined
      || (Array.isArray(value) && value.length === 0)
      || (typeof value === 'object' && !Array.isArray(value) && Object.keys(value).length === 0);
    return isEmpty
      ? `${header}：（暂无）`
      : `${header}：\n${JSON.stringify(value, null, 2)}`;
  }).join('\n\n');
}

export function buildUserPrompt(options = {}) {
  const { task, context = null, schemaHint = '', mode = MODES.GATHER } = options;
  const schema = schemaHint !== '' ? schemaHint : buildSchema(mode);
  const parts = [
    '以下是本轮对话可以参考的上下文：',
    renderContext(context),
    `任务：${task}`,
    `输出 JSON 结构要求：\n${schema}`
  ];
  parts.push('请直接输出 JSON。');
  return parts.join('\n\n');
}

export function buildMessages(options = {}) {
  const { task, context, schemaHint, rules, system, mode = MODES.GATHER } = options;
  return [
    { role: 'system', content: system ?? buildSystemPrompt({ extraRules: rules }) },
    { role: 'user', content: buildUserPrompt({ task, context, schemaHint, mode }) }
  ];
}
